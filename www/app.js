/** The label as the printer's columns, left to right: height/8 bytes each, topmost dot = MSB. */
function labelColumns(label) {
  const { canvas, width, height } = label;
  const px = canvas.getContext('2d', { willReadFrequently: true }).getImageData(0, 0, width, height).data;
  const bytesPerColumn = height / 8;
  const out = new Uint8Array(width * bytesPerColumn);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (px[(y * width + x) * 4] < 128) out[x * bytesPerColumn + (y >> 3)] |= 0x80 >> (y & 7);
    }
  }
  return out;
}

async function printLabel() {
  if (state.printing) return;
  if (!state.design.elements.length) {
    toast(t('The label is empty.'), true);
    return;
  }
  const button = $('#print');
  state.printing = true;
  button.disabled = true;
  button.textContent = t('Printing …');
  try {
    await loadDesignFonts();
    await prepareForPrint();
    const label = renderLabel();
    if (label.tooLong) {
      throw new Error(t('The label is longer than {mm} mm, the most labelbee prints.',
        { mm: Math.floor(state.config.maxWidthPx / state.config.dotsPerMm) }));
    }
    const params = new URLSearchParams({ tape: state.design.tape, width: label.width });
    if (state.config.printer.state !== 'ready') button.textContent = t('Printer is starting …');
    const response = await fetch(`/api/print?${params}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/octet-stream' },
      body: labelColumns(label),
    });
    const body = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(I18N.server(body.error) || `HTTP ${response.status}`);
    toast(t('Printed'));
    refreshStatus();
  } catch (e) {
    toast(t('Printing failed: {error}', { error: e.message }), true);
  } finally {
    state.printing = false;
    button.disabled = false;
    button.textContent = t('Print');
  }
}

