function moveLayer(el, delta) {
  const list = state.design.elements;
  const i = list.indexOf(el);
  const j = i + delta;
  if (j < 0 || j >= list.length) return;
  [list[i], list[j]] = [list[j], list[i]];
  commit();
  render();
  renderLayers();
}

