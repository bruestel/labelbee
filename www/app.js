function nextFreeX() {
  const d = state.design;
  if (!d.elements.length) return 0;
  const x = Math.max(...d.elements.map((el) => { const b = box(el); return b.x + b.w; })) + 8;
  if (d.lengthMode === 'fixed' && x >= labelWidthFixed() - 2 * paddingPx(d) - 8) return 4;
  return x;
}

