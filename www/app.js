/** Input bound to `el[prop]`; renders live, records history when editing ends. */
function bound(el, prop, { type = 'text', min, max, step, list, onInput } = {}) {
  const input = document.createElement(type === 'textarea' ? 'textarea' : 'input');
  if (type !== 'textarea') input.type = type;
  if (type === 'checkbox') input.checked = !!el[prop]; else input.value = el[prop];
  if (min !== undefined) input.min = min;
  if (max !== undefined) input.max = max;
  if (step !== undefined) input.step = step;
  if (list) input.setAttribute('list', list);
  input.dataset.prop = prop;
  input.addEventListener(type === 'checkbox' ? 'change' : 'input', () => {
    let value = input.value;
    if (type === 'checkbox') value = input.checked;
    if (type === 'number' || type === 'range') {
      value = Number(input.value);
      if (!Number.isFinite(value) || input.value === '') return;
      if (min !== undefined) value = Math.max(min, value);
      if (max !== undefined) value = Math.min(max, value);
    }
    el[prop] = value;
    onInput?.(value);
    render();
    renderLayers();
  });
  input.addEventListener('change', commit);
  return input;
}

function boundSelect(el, prop, options, onChange) {
  const sel = document.createElement('select');
  for (const [value, text] of options) {
    if (!Array.isArray(text)) {
      sel.add(new Option(text, value));
      continue;
    }
    // [group label, [[value, text], ...]]
    const group = document.createElement('optgroup');
    group.label = value;
    for (const [v, t] of text) group.append(new Option(t, v));
    sel.append(group);
  }
  sel.value = el[prop];
  sel.addEventListener('change', () => {
    el[prop] = sel.value;
    onChange?.();
    commit();
    render();
    renderLayers();
    updateCodeError();
  });
  return sel;
}

