/** Before replacing the design: offers to save unsaved changes. Resolves false to stay. */
async function confirmDiscard() {
  if (!isDirty() || !state.design.elements.length && !state.templateName) return true;
  const question = state.templateName
    ? t('"{name}" has unsaved changes. Save them first?', { name: state.templateName })
    : t('The label has unsaved changes. Save them first?');
  const answer = await ask(question,
    [['save', t('Save'), 'primary'], ['discard', t('Don\'t save')], ['cancel', t('Cancel')]]);
  if (answer === 'discard') return true;
  if (answer !== 'save') return false;
  return saveFile();   // without a name this opens "Save as" and stays
}

