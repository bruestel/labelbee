function toDesign(e) {
  const rect = canvas.getBoundingClientRect();
  const z = state.zoom;
  return {
    x: (e.clientX - rect.left - state.view.originX) / z - state.view.offsetX,
    y: (e.clientY - rect.top - state.view.originY) / z,
  };
}

function hitTest(p) {
  const tolerance = 3 / state.zoom + 1;
  return [...state.design.elements].reverse().find((el) => {
    const b = box(el);
    return p.x >= b.x - tolerance && p.x <= b.x + b.w + tolerance
      && p.y >= b.y - tolerance && p.y <= b.y + b.h + tolerance;
  }) || null;
}

// ---------- Resize handles ----------

const RESIZE_CURSORS = { nw: 'nwse-resize', se: 'nwse-resize', ne: 'nesw-resize', sw: 'nesw-resize',
  n: 'ns-resize', s: 'ns-resize', e: 'ew-resize', w: 'ew-resize' };

/** The selected element's resize handles in design coordinates: corners, for frames also edge midpoints. */
function handles(el) {
  if (!['rect', 'image', 'icon', 'text'].includes(el.type)) return [];
  const b = box(el);
  const x0 = b.x, x1 = b.x + b.w, y0 = b.y, y1 = b.y + b.h, xm = (x0 + x1) / 2, ym = (y0 + y1) / 2;
  const list = [
    { dir: 'nw', x: x0, y: y0 }, { dir: 'ne', x: x1, y: y0 },
    { dir: 'sw', x: x0, y: y1 }, { dir: 'se', x: x1, y: y1 },
  ];
  if (el.type === 'rect') {
    list.push({ dir: 'n', x: xm, y: y0 }, { dir: 's', x: xm, y: y1 }, { dir: 'w', x: x0, y: ym }, { dir: 'e', x: x1, y: ym });
  }
  return list;
}

/** A handle's position on the canvas in CSS pixels (matches the selection frame in render()). */
function handleScreen(h) {
  const { originX, originY, offsetX } = state.view;
  const z = state.zoom;
  return { x: originX + (h.x + offsetX) * z, y: originY + h.y * z };
}

function handleAt(e) {
  const el = selected();
  if (!el) return null;
  const rect = canvas.getBoundingClientRect();
  const mx = e.clientX - rect.left, my = e.clientY - rect.top;
  const reach = HANDLE_PX / 2 + 3;
  return handles(el).find((h) => {
    const p = handleScreen(h);
    return Math.abs(p.x - mx) <= reach && Math.abs(p.y - my) <= reach;
  }) || null;
}

/** Applies a handle drag: dx/dy in dots since the drag started; the opposite side stays put. */
function resizeElement(el, drag, dx, dy) {
  const o = drag.orig, dir = drag.dir;
  const sx = dir.includes('e') ? 1 : dir.includes('w') ? -1 : 0;
  const sy = dir.includes('s') ? 1 : dir.includes('n') ? -1 : 0;
  if (el.type === 'text') {
    // Scale the font size with the box height; the opposite corner stays put.
    const d = (sx * dx * o.h / Math.max(1, o.w) + sy * dy) / 2;
    el.size = clamp(Math.round(o.size * (o.h + d) / Math.max(1, o.h)), 4, 400);
    const b = box(el);
    el.x = sx < 0 ? o.x + o.w - b.w : o.x;
    el.y = sy < 0 ? o.y + o.h - b.h : o.y;
    return;
  }
  if (el.type === 'icon') {
    const d = sx && sy ? (sx * dx + sy * dy) / 2 : sx ? sx * dx : sy * dy;
    const size = clamp(Math.round(o.size + d), 4, 400);
    el.size = size;
    el.x = sx < 0 ? o.x + o.size - size : o.x;
    el.y = sy < 0 ? o.y + o.size - size : o.y;
    return;
  }
  let w = clamp(Math.round(o.w + sx * dx), 1, 5000);
  let h = clamp(Math.round(o.h + sy * dy), 1, 200);
  if (el.type === 'image' && el.lockAspect && o.w > 0 && o.h > 0) {
    const aspect = o.w / o.h;
    // follow the axis that moved more
    if (Math.abs(dx) * o.h >= Math.abs(dy) * o.w) h = clamp(Math.round(w / aspect), 1, 200);
    else w = clamp(Math.round(h * aspect), 1, 5000);
  }
  el.w = w;
  el.h = h;
  el.x = sx < 0 ? o.x + o.w - w : o.x;
  el.y = sy < 0 ? o.y + o.h - h : o.y;
}

canvas.addEventListener('pointerdown', (e) => {
  const handle = handleAt(e);
  if (handle) {
    const el = selected();
    state.drag = {
      id: el.id, dir: handle.dir, resize: true, clientX: e.clientX, clientY: e.clientY, moved: false,
      orig: { x: el.x, y: el.y, w: el.w, h: el.h, size: el.size, ...(el.type === 'text' ? { w: box(el).w, h: box(el).h } : {}) },
    };
    canvas.setPointerCapture(e.pointerId);
    e.preventDefault();
    return;
  }
  const hit = hitTest(toDesign(e));
  select(hit?.id ?? null);
  if (!hit) return;
  state.drag = { id: hit.id, clientX: e.clientX, clientY: e.clientY, x: hit.x, y: hit.y, moved: false };
  canvas.setPointerCapture(e.pointerId);
  e.preventDefault();
});

canvas.addEventListener('pointermove', (e) => {
  const drag = state.drag;
  if (!drag) {
    const handle = handleAt(e);
    canvas.style.cursor = handle ? RESIZE_CURSORS[handle.dir] : hitTest(toDesign(e)) ? 'move' : 'default';
    return;
  }
  const el = selected();
  if (!el) return;
  if (drag.resize) {
    const before = JSON.stringify([el.x, el.y, el.w, el.h, el.size]);
    resizeElement(el, drag, (e.clientX - drag.clientX) / state.zoom, (e.clientY - drag.clientY) / state.zoom);
    if (JSON.stringify([el.x, el.y, el.w, el.h, el.size]) !== before) {
      drag.moved = true;
      render();
      syncPropInputs();
      renderLayers();
    }
    return;
  }
  // Client deltas, so the moving auto-length offset does not feed back into the drag.
  const x = Math.round(drag.x + (e.clientX - drag.clientX) / state.zoom);
  const y = Math.round(drag.y + (e.clientY - drag.clientY) / state.zoom);
  if (x !== el.x || y !== el.y) {
    el.x = x;
    el.y = y;
    drag.moved = true;
    render();
    syncPropInputs();
  }
});

function endDrag() {
  if (state.drag?.moved) commit();
  state.drag = null;
}
