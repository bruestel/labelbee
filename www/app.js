const measureCtx = makeCanvas(1, 1).getContext('2d');

function fontString(el) {
  let family = (el.font || 'sans-serif').trim();
  if (!GENERIC_FONTS.includes(family) && !/^["']/.test(family)) family = `"${family.replace(/"/g, '')}"`;
  return `${el.italic ? 'italic ' : ''}${el.bold ? 'bold ' : ''}${el.size}px ${family}`;
}

const textLayoutCache = new Map();

function textLayout(el) {
  const key = `${fontString(el)}|${el.lineHeight}|${el.text}`;
  const cached = textLayoutCache.get(key);
  if (cached) return cached;
  const layout = measureText(el);
  if (textLayoutCache.size > 500) textLayoutCache.clear();
  // Only cache what was measured with the real font, not a fallback.
  if (fontReady(fontString(el))) textLayoutCache.set(key, layout);
  return layout;
}

function measureText(el) {
  measureCtx.font = fontString(el);
  const lines = String(el.text ?? '').split('\n');
  const m = measureCtx.measureText('ÄÖÜgjpqy');
  const ascent = m.fontBoundingBoxAscent ?? el.size * 0.8;
  const descent = m.fontBoundingBoxDescent ?? el.size * 0.2;
  const lineHeight = (ascent + descent) * (el.lineHeight || 1);
  const widths = lines.map((line) => measureCtx.measureText(line).width);
  return {
    lines, widths, ascent, lineHeight,
    w: Math.max(1, ...widths),
    h: lineHeight * (lines.length - 1) + ascent + descent,
  };
}

/** Layout box in label dots, used for hit testing, selection and auto length. */
function box(el) {
  switch (el.type) {
    case 'text': {
      const l = textLayout(el);
      return { x: el.x, y: el.y, w: Math.ceil(l.w), h: Math.ceil(l.h) };
    }
    case 'qr': {
      const n = codeMatrix(el)?.width ?? 21;
      const s = qrScale(el, n);
      return { x: el.x, y: el.y, w: n * s, h: n * s };
    }
    case 'barcode': {
      const n = codeMatrix(el)?.width ?? 60;
      return { x: el.x, y: el.y, w: n * el.module, h: el.h };
    }
    case 'icon':
      return { x: el.x, y: el.y, w: el.size, h: el.size };
    default:
      return { x: el.x, y: el.y, w: el.w, h: el.h };
  }
}

function drawElement(ctx, el) {
  ctx.fillStyle = '#000';
  switch (el.type) {
    case 'text': {
      const l = textLayout(el);
      if (el.invert) ctx.fillRect(el.x, el.y, Math.ceil(l.w), Math.ceil(l.h));
      ctx.font = fontString(el);
      ctx.fillStyle = el.invert ? '#fff' : '#000';
      ctx.textBaseline = 'alphabetic';
      ctx.textAlign = 'left';
      l.lines.forEach((line, i) => {
        const free = l.w - l.widths[i];
        const dx = el.align === 'center' ? free / 2 : el.align === 'right' ? free : 0;
        ctx.fillText(line, el.x + dx, el.y + l.ascent + i * l.lineHeight);
      });
      break;
    }
    case 'qr': {
      const m = codeMatrix(el);
      if (!m) break;
      const s = qrScale(el, m.width);
      for (let y = 0; y < m.height; y++) {
        for (let x = 0; x < m.width; x++) {
          if (m.modules[y * m.width + x] === '1') ctx.fillRect(el.x + x * s, el.y + y * s, s, s);
        }
      }
      break;
    }
    case 'barcode': {
      const m = codeMatrix(el);
      if (!m) break;
      for (let x = 0; x < m.width; x++) {
        if (m.modules[x] === '1') ctx.fillRect(el.x + x * el.module, el.y, el.module, el.h);
      }
      break;
    }
    case 'image': {
      const c = processedImage(el);
      if (c) ctx.drawImage(c, el.x, el.y);
      break;
    }
    case 'icon': {
      const font = elementFont(el);
      if (!el.code || !fontReady(font)) break;
      ctx.font = font;
      ctx.textAlign = 'center';
      ctx.textBaseline = 'middle';
      ctx.fillText(String.fromCodePoint(el.code), el.x + el.size / 2, el.y + el.size / 2);
      break;
    }
    case 'rect': {
      if (el.fill) {
        ctx.fillRect(el.x, el.y, el.w, el.h);
      } else {
        const s = Math.min(el.stroke, el.w / 2, el.h / 2);
        ctx.fillRect(el.x, el.y, el.w, s);
        ctx.fillRect(el.x, el.y + el.h - s, el.w, s);
        ctx.fillRect(el.x, el.y, s, el.h);
        ctx.fillRect(el.x + el.w - s, el.y, s, el.h);
      }
      break;
    }
  }
}

/** Forces every pixel to pure black or white; returns an ink layer (black on transparent). */
function threshold(canvas) {
  const ctx = canvas.getContext('2d', { willReadFrequently: true });
  const data = ctx.getImageData(0, 0, canvas.width, canvas.height);
  const ink = new ImageData(canvas.width, canvas.height);
  const px = data.data;
  for (let i = 0; i < px.length; i += 4) {
    const black = 0.299 * px[i] + 0.587 * px[i + 1] + 0.114 * px[i + 2] < 128;
    px[i] = px[i + 1] = px[i + 2] = black ? 0 : 255;
    px[i + 3] = 255;
    ink.data[i + 3] = black ? 255 : 0;
  }
  ctx.putImageData(data, 0, 0);
  const inkCanvas = makeCanvas(canvas.width, canvas.height);
  inkCanvas.getContext('2d').putImageData(ink, 0, 0);
  return inkCanvas;
}

/** Renders the printable label: exactly tape height, 1 px per dot. */
function renderLabel() {
  const d = state.design;
  const H = tapeHeight();
  let width, offsetX;
  const pad = paddingPx(d);
  if (d.lengthMode === 'fixed') {
    // the fixed length is the whole label; the margin lies inside it, element positions count from it
    width = Math.max(labelWidthFixed(), 2 * pad + 1);
    offsetX = pad;
  } else if (d.elements.length) {
    const boxes = d.elements.map(box);
    const minX = Math.min(...boxes.map((b) => b.x));
    const maxX = Math.max(...boxes.map((b) => b.x + b.w));
    width = Math.ceil(maxX - minX) + 2 * pad;
    offsetX = pad - minX;
  } else {
    width = Math.max(16, 2 * pad);
    offsetX = pad;
  }
  const tooLong = Math.round(width) > state.config.maxWidthPx;
  width = clamp(Math.round(width), 1, state.config.maxWidthPx);

  const canvas = makeCanvas(width, H);
  const ctx = canvas.getContext('2d', { willReadFrequently: true });
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, width, H);
  ctx.translate(offsetX, 0);
  ctx.imageSmoothingEnabled = false;
  for (const el of d.elements) drawElement(ctx, el);
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  const ink = threshold(canvas);
  return { canvas, ink, width, height: H, offsetX, tooLong };
}

/** Bounding box of the actually printed pixels of one element (design coordinates). */
function inkBounds(el) {
  const b = box(el);
  const pad = Math.ceil(b.h / 2) + 8; // italics and accents may leave the layout box
  const w = Math.ceil(b.w) + 2 * pad, h = Math.ceil(b.h) + 2 * pad;
  const c = makeCanvas(w, h);
  const ctx = c.getContext('2d', { willReadFrequently: true });
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, w, h);
  ctx.translate(pad - b.x, pad - b.y);
  drawElement(ctx, el);
  const px = ctx.getImageData(0, 0, w, h).data;
  let minX = w, minY = h, maxX = -1, maxY = -1;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (px[(y * w + x) * 4] < 128) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (maxX < 0) return null;
  return { x: minX - pad + b.x, y: minY - pad + b.y, w: maxX - minX + 1, h: maxY - minY + 1 };
}

// ---------- Layout tools ----------

// No margin for "fill the height": the print band (64 dots on 12 mm) already sits inside the tape.
const tapeMargin = () => 0;

const usesInk = (el) => el.type === 'text' || el.type === 'icon';

function centerVertically(el) {
  const ink = usesInk(el) ? inkBounds(el) : box(el);
  if (ink) el.y += Math.round((tapeHeight() - ink.h) / 2 - ink.y);
}

function centerHorizontally(el) {
  const ink = usesInk(el) ? inkBounds(el) : box(el);
  if (ink) el.x += Math.round((labelWidthFixed() - 2 * paddingPx() - ink.w) / 2 - ink.x);
}

function fitToHeight(el) {
  const H = tapeHeight();
  const target = H - 2 * tapeMargin();
  switch (el.type) {
    case 'text': {
      let lo = 4, hi = 400;
      while (lo < hi) {
        const mid = Math.ceil((lo + hi) / 2);
        el.size = mid;
        const ink = inkBounds(el);
        if (!ink || ink.h <= target) lo = mid; else hi = mid - 1;
      }
      el.size = lo;
      break;
    }
    case 'qr':
      el.scale = 0;
      break;
    case 'barcode':
      el.h = target;
      break;
    case 'image': {
      const aspect = el.w / el.h;
      el.h = H;
      el.w = Math.max(1, Math.round(H * aspect));
      break;
    }
    case 'rect':
      el.h = target;
      break;
    case 'icon': {
      // The glyphs leave a margin inside their em box: size the box so the ink fills the target.
      el.size = target;
      const ink = inkBounds(el);
      if (ink && ink.h > 0) el.size = Math.max(4, Math.round(target * target / ink.h));
      break;
    }
  }
  centerVertically(el);
}

/** Keeps the layout when switching tapes by scaling everything to the new height. */
function scaleDesign(factor) {
  const r = (v) => Math.round(v * factor);
  for (const el of state.design.elements) {
    el.x = r(el.x);
    el.y = r(el.y);
    if (el.type === 'text') el.size = Math.max(4, r(el.size));
    if (el.type === 'qr' && el.scale > 0) el.scale = Math.max(1, Math.floor(el.scale * factor));
    if (el.type === 'barcode') el.h = Math.max(4, r(el.h));
    if (el.type === 'image' || el.type === 'rect') {
      el.w = Math.max(1, r(el.w));
      el.h = Math.max(1, r(el.h));
    }
    if (el.type === 'rect') el.stroke = Math.max(1, r(el.stroke));
    if (el.type === 'icon') el.size = Math.max(4, r(el.size));
  }
}

// ---------- Stage rendering ----------

const canvas = $('#canvas');
let lastLabel = null;

function render() {
  if (!state.design) return;
  const label = renderLabel();
  lastLabel = label;
  const d = state.design;
  const z = state.zoom;
  const dpmm = state.config.dotsPerMm;
  const tapePx = TAPE_MM[d.tape] * dpmm;
  const overhang = Math.round(TAPE_OVERHANG_MM * dpmm);

  const cssW = (label.width + 2 * overhang) * z;
  const cssH = Math.round(tapePx * z);
  const dpr = Math.min(window.devicePixelRatio || 1, 16000 / cssW);
  canvas.style.width = `${cssW}px`;
  canvas.style.height = `${cssH}px`;
  canvas.width = Math.round(cssW * dpr);
  canvas.height = Math.round(cssH * dpr);

  const ctx = canvas.getContext('2d');
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, cssW, cssH);

  // Tape
  ctx.save();
  ctx.shadowColor = 'rgba(0,0,0,.35)';
  ctx.shadowBlur = 12;
  ctx.shadowOffsetY = 3;
  const style = TAPE_STYLES[d.tapeStyle] || TAPE_STYLES['black-white'];
  ctx.fillStyle = style.tape;
  ctx.beginPath();
  ctx.roundRect(0, 0, cssW, cssH, 4);
  ctx.fill();
  ctx.restore();

  const originX = overhang * z;
  const originY = Math.round(((tapePx - label.height) / 2) * z);
  state.view = { originX, originY, offsetX: label.offsetX };

  // Printable band and cut lines
  ctx.strokeStyle = 'rgba(0,0,0,.18)';
  ctx.lineWidth = 1;
  ctx.setLineDash([4, 4]);
  ctx.beginPath();
  ctx.moveTo(0, originY - 0.5);
  ctx.lineTo(cssW, originY - 0.5);
  ctx.moveTo(0, originY + label.height * z + 0.5);
  ctx.lineTo(cssW, originY + label.height * z + 0.5);
  ctx.stroke();
  ctx.strokeStyle = 'rgba(0,0,0,.45)';
  ctx.setLineDash([6, 4]);
  ctx.beginPath();
  for (const x of [originX - 0.5, originX + label.width * z + 0.5]) {
    ctx.moveTo(x, 0);
    ctx.lineTo(x, cssH);
  }
  ctx.stroke();
  // the margin, when there is one
  const pad = paddingPx(d);
  if (pad > 0) {
    ctx.strokeStyle = 'rgba(0,0,0,.22)';
    ctx.setLineDash([2, 4]);
    ctx.beginPath();
    for (const x of [originX + pad * z - 0.5, originX + (label.width - pad) * z + 0.5]) {
      ctx.moveTo(x, originY);
      ctx.lineTo(x, originY + label.height * z);
    }
    ctx.stroke();
  }
  ctx.setLineDash([]);

  // Printed dots, in the print colour of the chosen tape
  let ink = label.ink;
  if (style.ink !== '#111111') {
    ink = makeCanvas(label.width, label.height);
    const ictx = ink.getContext('2d');
    ictx.drawImage(label.ink, 0, 0);
    ictx.globalCompositeOperation = 'source-in';
    ictx.fillStyle = style.ink;
    ictx.fillRect(0, 0, label.width, label.height);
  }
  ctx.imageSmoothingEnabled = false;
  ctx.globalAlpha = 0.92;
  ctx.drawImage(ink, originX, originY, label.width * z, label.height * z);
  ctx.globalAlpha = 1;

  // Selection
  const el = selected();
  if (el) {
    const b = box(el);
    ctx.strokeStyle = getComputedStyle(document.documentElement).getPropertyValue('--select').trim() || '#3ba7f2';
    ctx.lineWidth = 2;
    ctx.strokeRect(
      originX + (b.x + label.offsetX) * z - 1, originY + b.y * z - 1,
      b.w * z + 2, b.h * z + 2,
    );
    ctx.fillStyle = '#fff';
    ctx.lineWidth = 1.5;
    for (const h of handles(el)) {
      const p = handleScreen(h);
      ctx.fillRect(p.x - HANDLE_PX / 2, p.y - HANDLE_PX / 2, HANDLE_PX, HANDLE_PX);
      ctx.strokeRect(p.x - HANDLE_PX / 2, p.y - HANDLE_PX / 2, HANDLE_PX, HANDLE_PX);
    }
  }

  const mm = (label.width / dpmm).toFixed(1).replace('.', ',');
  const feedMm = Math.round((label.width + 113) / dpmm);   // + the firmware's 113 trailing lines (label.cpp)
  const file = state.templateName ? escapeHtml(state.templateName) : t('Untitled');
  $('#label-info').innerHTML =
    `<span class="file${state.dirty ? ' dirty' : ''}" title="${state.dirty ? t('Unsaved changes') : t('Saved')}">${file}</span> · ${t('Length')} <strong>${mm} mm</strong> · ${label.width} × ${label.height} px · ` +
    `${t('Tape')} ${TAPE_MM[d.tape]} mm · ${t('uses')} ≈ ${feedMm} mm`;
  $('#zoom-value').textContent = `${String(z).replace('.', ',')}×`;
}

/** Whole-number zoom keeps dots crisp; below 4× quarter steps are allowed for long labels. */
function snapZoom(z) {
  return clamp(z >= 4 ? Math.floor(z) : Math.floor(z * 4) / 4, 0.5, MAX_ZOOM);
}

function stepZoom(direction) {
  const step = (direction > 0 ? state.zoom >= 4 : state.zoom > 4) ? 1 : 0.5;
  state.zoom = snapZoom(state.zoom + direction * step);
  render();
}

function fitZoom() {
  const wrap = $('#canvas-wrap');
  const label = renderLabel();
  const dpmm = state.config.dotsPerMm;
  const totalW = label.width + 2 * Math.round(TAPE_OVERHANG_MM * dpmm);
  const tapePx = TAPE_MM[state.design.tape] * dpmm;
  const byWidth = (wrap.clientWidth - 48) / totalW;
  const byHeight = (Math.max(wrap.clientHeight, 220) - 48) / tapePx;
  state.zoom = snapZoom(Math.min(byWidth, byHeight));
  render();
}

