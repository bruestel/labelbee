async function refreshStatus() {
  try {
    const status = await api('/api/status');
    const tapesChanged = JSON.stringify(status.tapes) !== JSON.stringify(state.config.tapes);
    Object.assign(state.config, status);
    state.online = true;
    if (tapesChanged) buildTapeOptions();
  } catch {
    state.online = false;
  }
  updateStatus();
}

function buildTapeOptions() {
  const select = $('#tape');
  select.replaceChildren(...state.config.tapes.map((t) => new Option(`${t.description} · ${t.heightPx} px`, t.id)));
  if (state.design) select.value = state.design.tape;
}

function updateStatus() {
  const el = $('#printer-status');
  const p = state.config.printer;
  let mode, text;
  if (state.online === false) {
    mode = 'missing'; text = t('labelbee cannot be reached');
  } else if (p.state === 'off') {
    mode = 'dry'; text = t('Printer switched off');
  } else if (p.state === 'starting') {
    mode = 'unknown'; text = t('Printer is starting …');
  } else if (p.state === 'missing') {
    mode = 'missing'; text = t('Printer does not respond. Connected?');
  } else if (p.state === 'ready' && !p.cassette) {
    mode = 'missing'; text = t('No tape inserted');
  } else if (p.state === 'ready') {
    mode = 'ok';
    const battery = p.statusKnown ? ` · ${t('battery {n} %', { n: p.batteryPercent })}${p.charging ? `, ${t('charging')}` : ''}` : '';
    text = `${p.model || t('Printer')} ${p.busy ? t('printing …') : t('ready')}${battery}`;
  } else {
    mode = 'unknown'; text = t('Connecting …');
  }
  el.dataset.state = mode;
  const label = el.querySelector('.label');
  label.textContent = text;
  if (p.state === 'off' && state.online !== false) {
    // a link to the settings page, where it is switched on
    label.textContent = `${t('Printer switched off')}: `;
    const a = document.createElement('a');
    a.href = '/settings';
    a.textContent = t('switch on in the settings');
    label.append(a);
  }
}

