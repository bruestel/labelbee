function renderTemplates() {
  const list = $('#templates');
  list.replaceChildren();
  const all = Object.keys(state.templates);
  const query = $('#template-search').value.trim().toLowerCase();
  // newest first, files without a date (saved before dates were kept) at the end
  const names = all.filter((n) => n.toLowerCase().includes(query)).sort((a, b) =>
    savedTime(state.templates[b]).localeCompare(savedTime(state.templates[a]))
    || a.localeCompare(b, I18N.locale));
  if (!names.length) {
    list.innerHTML = all.length
      ? `<li class="icon-empty"><strong>${t('No file found')}</strong></li>`
      : `<li class="icon-empty"><strong>${t('No files yet')}</strong>${t('Design a label and save it below under a name.')}</li>`;
    return;
  }
  for (const name of names) {
    const li = document.createElement('li');
    li.className = 'template-card';
    if (name === state.templateName) li.classList.add('current');
    const open = document.createElement('button');
    open.type = 'button';
    open.className = 'template-open';
    open.title = t('Open "{name}"', { name });
    const preview = document.createElement('span');
    preview.className = 'template-preview';
    const thumb = templatePreview(state.templates[name]);
    if (thumb) preview.append(thumb);
    const span = document.createElement('span');
    span.className = 'name';
    span.textContent = name;
    const when = document.createElement('span');
    when.className = 'when';
    when.textContent = formatSavedAt(savedTime(state.templates[name])) || t('no date');
    open.append(preview, span, when);
    open.addEventListener('click', async () => {
      if (name !== state.templateName && !(await confirmDiscard())) return;
      openTemplate(name);
      $('#template-dialog').close();
    });
    li.append(open);

    // Two clicks to delete, no modal dialog.
    const del = iconButton('✕', t('Delete file'), async () => {
      if (!del.classList.contains('danger')) {
        del.classList.add('danger');
        del.textContent = t('Delete?');
        setTimeout(() => { del.classList.remove('danger'); del.textContent = '✕'; }, 3000);
        return;
      }
      try {
        await api(`/api/templates/${encodeURIComponent(name)}`, { method: 'DELETE' });
        delete state.templates[name];
        if (state.templateName === name) {
          state.templateName = '';
          state.savedSnapshot = null;
          persistFile();
          render();
        }
        renderTemplates();
        toast(t('Deleted "{name}"', { name }));
      } catch (e) {
        toast(e.message, true);
      }
    });
    del.classList.add('template-delete');
    li.append(del);
    list.append(li);
  }
}

function openTemplate(name) {
  const design = structuredClone(state.templates[name]);
  delete design.savedAt;
  delete design._mtime;
  state.design = normalizeDesign(design);
  state.selectedId = null;
  commit();
  markSaved(name);
  refreshAll();
  fitZoom();
}

/**
 * Saves the design under the name (default: the open file's). Without a name yet, the dialog asks
 * for one. Resolves true once saved.
 */
async function saveFile(name = state.templateName) {
  name = name.trim();
  if (!name) {
    openFileDialog({ saveAs: true });
    return false;
  }
  try {
    if (await shrinkDesignImages(state.design)) {
      commit();
      render();
    }
    const stored = { ...JSON.parse(snapshot()), savedAt: new Date().toISOString() };
    const body = JSON.stringify(stored);
    const bytes = new Blob([body]).size;
    if (bytes > TEMPLATE_MAX_BYTES) {
      toast(t('The label is too large at {kb} KB (at most {max} KB). ', { kb: Math.round(bytes / 1024), max: TEMPLATE_MAX_BYTES / 1024 })
        + t('Use fewer or smaller images.'), true);
      return false;
    }
    const existed = Object.hasOwn(state.templates, name);
    await api(`/api/templates/${encodeURIComponent(name)}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body,
    });
    state.templates[name] = stored;
    markSaved(name);
    renderTemplates();
    toast(existed ? t('Saved "{name}"', { name }) : t('Created "{name}"', { name }));
    return true;
  } catch (e) {
    toast(t('Saving failed: {error}', { error: e.message }), true);
    return false;
  }
}

