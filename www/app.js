const fontRequests = new Set();

/** Is the font of a CSS font string ready for the canvas? If not, loads it and renders again when it arrives. */
/**
 * Whether the face a CSS font string uses is loaded. document.fonts.check() is not enough: for a
 * weight without its own face (bold of a single-weight font) it reports true before anything loaded.
 */
function fontLoaded(css) {
  if (!document.fonts.check(css)) return false;
  const family = css.replace(/^.*?\d+px\s+/, '').replace(/["']/g, '').trim();
  const faces = [...document.fonts].filter((f) => f.family.replace(/["']/g, '') === family);
  if (!faces.length) return true;   // a system font
  const weight = /\bbold\b/.test(css) ? '700' : '400';
  const style = /\bitalic\b/.test(css) ? 'italic' : 'normal';
  const exact = faces.filter((f) => f.weight === weight && f.style === style);
  const used = exact.length ? exact : faces.filter((f) => f.weight === '400' && f.style === 'normal');
  return (used.length ? used : faces).every((f) => f.status === 'loaded');
}

function fontReady(css) {
  if (!document.fonts || fontLoaded(css)) return true;
  if (!fontRequests.has(css)) {
    fontRequests.add(css);
    document.fonts.load(css).then(() => {
      textLayoutCache.clear();
      render();
    }).catch(() => {});
  }
  return false;
}

const elementFont = (el) => (el.type === 'icon' ? `${el.size}px "${ICON_FONT}"` : fontString(el));

/** Waits until every font the design uses is loaded (before measuring for printing). */
function loadDesignFonts(design = state.design) {
  if (!document.fonts) return Promise.resolve();
  const fonts = new Set(design.elements.filter((el) => el.type === 'text' || el.type === 'icon').map(elementFont));
  return Promise.all([...fonts].map((f) => document.fonts.load(f).catch(() => {}))).then(() => textLayoutCache.clear());
}

let mdiList = null; // [{ name, code }], decoded from vendor/mdi-names.js on first use
let mdiMap = null;

function mdiIcons() {
  if (mdiList) return mdiList;
  mdiList = [];
  mdiMap = new Map();
  let code = 0;
  for (const part of MDI_NAMES.split(' ')) {
    const [name, step] = part.split('~');
    code = step === undefined ? code + 1 : (mdiList.length ? code + parseInt(step, 16) : parseInt(step, 16));
    mdiList.push({ name, code });
    mdiMap.set(name, code);
  }
  return mdiList;
}

function mdiCode(name) {
  mdiIcons();
  return mdiMap.get(name) ?? 0;
}

let mdiMetaMap = null; // name -> { cats: [category numbers], words: "name alias alias" }

/** Categories and aliases from vendor/mdi-meta.js, decoded on first use. */
function mdiMeta() {
  if (mdiMetaMap) return mdiMetaMap;
  mdiMetaMap = new Map();
  if (typeof MDI_META === 'string') {
    for (const line of MDI_META.split('\n')) {
      const [name, cats, aliases] = line.split(':');
      mdiMetaMap.set(name, {
        cats: cats ? cats.split(',').map((c) => parseInt(c, 36)) : [],
        words: aliases ? aliases.replace(/,/g, ' ') : '',
      });
    }
  }
  return mdiMetaMap;
}

const NO_CATEGORY = -2;  // "Other": icons without a category
const ALL_CATEGORIES = -1;

/** The icons in `category` whose name or aliases contain every word of the query. */
function searchIcons(query, category = ALL_CATEGORIES) {
  const words = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  const meta = mdiMeta();
  return mdiIcons().filter((icon) => {
    const m = meta.get(icon.name);
    const cats = m ? m.cats : [];
    if (category === NO_CATEGORY ? cats.length : category >= 0 && !cats.includes(category)) return false;
    if (!words.length) return true;
    const hay = m && m.words ? `${icon.name} ${m.words}` : icon.name;
    return words.every((w) => hay.includes(w));
  });
}

