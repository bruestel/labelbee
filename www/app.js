// ---------- Design model ----------

let idCounter = 0;
const uid = () => `e${Date.now().toString(36)}${(idCounter++).toString(36)}`;
const clamp = (v, min, max) => Math.min(max, Math.max(min, v));

function tapeHeight(design = state.design) {
  return state.config.tapes.find((t) => t.id === design.tape)?.heightPx ?? 64;
}

/** The margin at both ends of the printed image, in dots (set in mm). */
function paddingPx(design = state.design) {
  return Math.max(0, Math.round((design.paddingMm || 0) * state.config.dotsPerMm));
}

function labelWidthFixed(design = state.design) {
  return Math.round(design.lengthMm * state.config.dotsPerMm);
}

function defaultDesign() {
  return {
    tape: '12mm', lengthMode: 'auto', lengthMm: 40, paddingMm: 0, tapeStyle: 'black-white',
    elements: [],
  };
}

function createElement(type, extra = {}) {
  const H = tapeHeight();
  const base = { id: uid(), type, x: 0, y: 0 };
  const defaults = {
    text: { text: 'Text', font: 'Roboto', size: Math.round(H * 0.6), bold: true, italic: false,
      align: 'left', lineHeight: 1, invert: false },
    qr: { data: 'https://example.com', scale: 0 },
    barcode: { kind: 'code128', data: '12345678', module: 2, h: H - 8, y: 4 },
    image: { src: '', w: H, h: H, dither: true, threshold: 128, invert: false, lockAspect: true },
    rect: { w: 60, h: H - 8, y: 4, stroke: 2, fill: false },
    icon: { name: 'tag-outline', code: mdiCode('tag-outline'), size: H - 8, y: 4 },
  };
  return { ...base, ...defaults[type], ...extra };
}

function normalizeDesign(raw) {
  const d = { ...defaultDesign(), ...(raw || {}) };
  if (!TAPE_MM[d.tape]) d.tape = '12mm';
  // older designs: the margin in dots, the tape colour alone
  if (raw && raw.paddingMm === undefined && Number.isFinite(raw.padding)) {
    d.paddingMm = Math.round((raw.padding / state.config.dotsPerMm) * 2) / 2;
  }
  delete d.padding;
  if (!TAPE_STYLES[d.tapeStyle]) d.tapeStyle = OLD_TAPE_COLORS[raw && raw.tapeColor] || 'black-white';
  delete d.tapeColor;
  d.elements = (Array.isArray(d.elements) ? d.elements : [])
    .filter((el) => el && TYPE_NAMES[el.type])
    .map((el) => ({ ...el, id: el.id || uid() }));
  return d;
}

const selected = () => state.design.elements.find((el) => el.id === state.selectedId) || null;

// ---------- History & persistence ----------

const snapshot = () => JSON.stringify(state.design);

function commit() {
  const s = snapshot();
  if (state.history[state.history.length - 1] !== s) {
    state.history.push(s);
    if (state.history.length > MAX_HISTORY) state.history.shift();
    state.future = [];
  }
  persist();
  updateUndoButtons();
}

function undo() {
  commit();
  if (state.history.length < 2) return;
  state.future.push(state.history.pop());
  restore(state.history[state.history.length - 1]);
}

function redo() {
  const s = state.future.pop();
  if (!s) return;
  state.history.push(s);
  restore(s);
}

function restore(s) {
  state.design = JSON.parse(s);
  if (!selected()) state.selectedId = null;
  persist();
  refreshAll();
}

function updateUndoButtons() {
  $('#undo').disabled = state.history.length < 2;
  $('#redo').disabled = state.future.length === 0;
}

function escapeHtml(text) {
  return String(text).replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);
}

function persist() {
  try { localStorage.setItem(STORAGE_KEY, snapshot()); } catch { /* quota or disabled storage */ }
  persistFile();
}

function loadPersisted() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? normalizeDesign(JSON.parse(raw)) : null;
  } catch {
    return null;
  }
}

// ---------- Codes (QR / barcodes, generated in the browser) ----------

qrcode.stringToBytes = qrcode.stringToBytesFuncs['UTF-8'];

const BARCODE_FORMATS = { code128: 'CODE128', code39: 'CODE39', ean13: 'EAN13' };

/** An invalid code: an English message key and its values, translated where it is shown. */
class CodeError extends Error {
  constructor(key, params) {
    super(key);
    this.key = key;
    this.params = params;
  }
}

/** The module matrix of a code: { width, height, modules } with modules row-major, '1' = dark. */
function makeMatrix(kind, data) {
  if (!data) throw new CodeError('No data');
  if (kind === 'qr') {
    // Low error correction keeps the module count small, which matters on 64 dots.
    const qr = qrcode(0, 'L');
    qr.addData(data);
    try {
      qr.make();
    } catch {
      throw new CodeError('Too much data for a QR code');
    }
    const n = qr.getModuleCount();
    let modules = '';
    for (let y = 0; y < n; y++) for (let x = 0; x < n; x++) modules += qr.isDark(y, x) ? '1' : '0';
    return { width: n, height: n, modules };
  }
  const format = BARCODE_FORMATS[kind];
  if (!format) throw new CodeError('Unknown code type "{kind}"', { kind });
  let valid = true;
  const out = {};
  try {
    JsBarcode(out, kind === 'code39' ? data.toUpperCase() : data, { format, flat: true, valid: (v) => { valid = v; } });
  } catch {
    valid = false;
  }
  if (!valid || !out.encodings) {
    throw new CodeError(kind === 'ean13' ? 'EAN-13 needs 12 or 13 digits' : 'This code cannot show these characters');
  }
  const bars = out.encodings.map((e) => e.data).join('');
  return { width: bars.length, height: 1, modules: bars };
}

const codes = new Map(); // "kind|data" -> { promise, matrix?, error? }
const lastMatrix = new Map(); // element id -> last successfully loaded matrix
const codeTimers = new Map();

const codeKind = (el) => (el.type === 'qr' ? 'qr' : el.kind);
const codeKey = (el) => `${codeKind(el)}|${el.data}`;

function fetchCode(kind, data) {
  const key = `${kind}|${data}`;
  if (codes.has(key)) return codes.get(key).promise;
  if (codes.size > 300) codes.clear();
  const entry = {};
  entry.promise = Promise.resolve()
    .then(() => { entry.matrix = makeMatrix(kind, data); })
    .catch((e) => { entry.error = e instanceof CodeError ? { key: e.key, params: e.params } : { key: e.message }; })
    .finally(() => { render(); updateCodeError(); });
  codes.set(key, entry);
  return entry.promise;
}

/**
 * Before printing: every code generated for its current data and every picture decoded, so the
 * print matches the design and not a placeholder from a moment ago. Throws on an invalid code.
 */
async function prepareForPrint() {
  for (const el of state.design.elements) {
    if (el.type === 'qr' || el.type === 'barcode') {
      await fetchCode(codeKind(el), el.data);
      const entry = codes.get(codeKey(el));
      if (entry?.error) throw new Error(t('Invalid: {error}', { error: codeError(el) }));
      if (entry?.matrix) lastMatrix.set(el.id, entry.matrix);
    } else if (el.type === 'image' && el.src) {
      loadedImage(el.src);
      await imageCache.get(el.src)?.decode().catch(() => {});
    }
  }
}

/** Returns the module matrix, falling back to the previous one while a new one loads. */
function codeMatrix(el) {
  const entry = codes.get(codeKey(el));
  if (entry?.matrix) {
    lastMatrix.set(el.id, entry.matrix);
    return entry.matrix;
  }
  if (!entry) {
    // Debounced, so typing does not fire a request per keystroke.
    clearTimeout(codeTimers.get(el.id));
    const kind = codeKind(el), data = el.data;
    codeTimers.set(el.id, setTimeout(() => fetchCode(kind, data), 200));
  }
  return lastMatrix.get(el.id) ?? null;
}

/** The code's error in the current language (kept as key and values, so a language switch applies). */
const codeError = (el) => {
  const error = codes.get(codeKey(el))?.error;
  return error ? t(error.key, error.params) : null;
};

function qrScale(el, modules) {
  return el.scale > 0 ? el.scale : Math.max(1, Math.floor(tapeHeight() / modules));
}

// ---------- Images ----------

const imageCache = new Map(); // src -> HTMLImageElement
const processedCache = new Map(); // element id -> { key, canvas }

function loadedImage(src) {
  if (!src) return null;
  let img = imageCache.get(src);
  if (!img) {
    img = new Image();
    img.onload = () => render();
    img.src = src;
    imageCache.set(src, img);
  }
  return img.complete && img.naturalWidth ? img : null;
}

function makeCanvas(w, h) {
  const c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  return c;
}

/** Scales an image to the element size and reduces it to 1 bit (white = transparent). */
function processedImage(el) {
  const img = loadedImage(el.src);
  if (!img) return null;
  const w = Math.max(1, Math.round(el.w)), h = Math.max(1, Math.round(el.h));
  const key = [el.src.length, el.src.slice(-32), w, h, el.dither, el.threshold, el.invert].join('|');
  const cached = processedCache.get(el.id);
  if (cached?.key === key) return cached.canvas;

  const c = makeCanvas(w, h);
  const ctx = c.getContext('2d', { willReadFrequently: true });
  ctx.fillStyle = '#fff';
  ctx.fillRect(0, 0, w, h);
  ctx.drawImage(img, 0, 0, w, h);
  const data = ctx.getImageData(0, 0, w, h);
  const px = data.data;
  const gray = new Float32Array(w * h);
  for (let i = 0; i < gray.length; i++) {
    const v = 0.299 * px[i * 4] + 0.587 * px[i * 4 + 1] + 0.114 * px[i * 4 + 2];
    gray[i] = el.invert ? 255 - v : v;
  }
  const spread = (x, y, amount) => {
    if (x >= 0 && x < w && y < h) gray[y * w + x] += amount;
  };
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      const old = gray[i];
      const value = old < el.threshold ? 0 : 255;
      gray[i] = value;
      if (el.dither) { // Floyd-Steinberg
        const err = old - value;
        spread(x + 1, y, err * 7 / 16);
        spread(x - 1, y + 1, err * 3 / 16);
        spread(x, y + 1, err * 5 / 16);
        spread(x + 1, y + 1, err / 16);
      }
    }
  }
  for (let i = 0; i < gray.length; i++) {
    px[i * 4] = px[i * 4 + 1] = px[i * 4 + 2] = 0;
    px[i * 4 + 3] = gray[i] === 0 ? 255 : 0;
  }
  ctx.putImageData(data, 0, 0);
  processedCache.set(el.id, { key, canvas: c });
  return c;
}

// Pictures are kept at no more than twice the tallest print height (64 dots), so designs
// and templates stay small: the firmware takes at most 512 KB per template.
const IMAGE_MAX_H = 128;
const IMAGE_MAX_W = 1024;
const TEMPLATE_MAX_BYTES = 512 * 1024;

function imageScale(w, h) {
  return Math.min(1, IMAGE_MAX_H / h, IMAGE_MAX_W / w);
}

/** A data URL of the picture, downscaled to the limits above (unchanged when it already fits). */
function shrinkImageSrc(src) {
  return new Promise((resolve) => {
    const img = new Image();
    img.onerror = () => resolve(src);
    img.onload = () => {
      const scale = imageScale(img.naturalWidth, img.naturalHeight);
      if (scale >= 1) return resolve(src);
      const c = makeCanvas(Math.max(1, Math.round(img.naturalWidth * scale)), Math.max(1, Math.round(img.naturalHeight * scale)));
      const ctx = c.getContext('2d');
      ctx.imageSmoothingQuality = 'high';
      ctx.drawImage(img, 0, 0, c.width, c.height);
      resolve(c.toDataURL('image/png'));
    };
    img.src = src;
  });
}

/** Downscales oversized pictures of a design in place (older designs kept them at up to 512 px). */
async function shrinkDesignImages(design) {
  let changed = false;
  for (const el of design.elements) {
    if (el.type !== 'image' || !el.src) continue;
    const src = await shrinkImageSrc(el.src);
    if (src !== el.src) {
      el.src = src;
      changed = true;
    }
  }
  return changed;
}

/** Reads an image file, downscaled so designs stay small. */
function readImageFile(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = () => reject(reader.error);
    reader.onload = () => {
      const img = new Image();
      img.onerror = () => reject(new Error(t('The image could not be read')));
      img.onload = () => {
        const scale = imageScale(img.naturalWidth, img.naturalHeight);
        const c = makeCanvas(Math.max(1, Math.round(img.naturalWidth * scale)), Math.max(1, Math.round(img.naturalHeight * scale)));
        c.getContext('2d').drawImage(img, 0, 0, c.width, c.height);
        resolve({ src: c.toDataURL('image/png'), aspect: c.width / c.height });
      };
      img.src = reader.result;
    };
    reader.readAsDataURL(file);
  });
}

