"""
Write www/vendor/mdi-meta.js: categories (English and German) and search aliases for the Material Design
Icons, from @mdi/svg's meta.json (same version as the font, 7.4.47):

    curl -sL -o meta.json https://unpkg.com/@mdi/svg@7.4.47/meta.json
    python3 tools/gen_mdi_meta.py meta.json

Format (decoded by mdiMeta() in www/app.js):
    MDI_CATEGORIES = [[English, German], ...]   (index = category number)
    MDI_META = "name:cats:aliases\\n..."  cats = category numbers in base 36, "," separated;
                                           aliases "," separated; icons without either are left out
"""

import json
import pathlib
import sys

