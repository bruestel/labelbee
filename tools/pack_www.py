"""
Pack the web interface (www/) into one blob the firmware serves (src/web.cpp).

Every file under www/ goes in, licence texts (LICENSE*) included, except *.md and *.py; its URL is its path
relative to www/. The blob lands in src/www_pack.bin with src/www_pack.S including it (.incbin);
both are generated, gitignored and rewritten only when the content changes, so a change in www/
always reaches the firmware and an unchanged www/ costs nothing.

A PlatformIO pre-build hook rather than a CMake rule or EMBED_FILES: PlatformIO does not run
ESP-IDF's embedding commands, and files generated when CMake configures go stale (CMake does not
configure again when only www/ changed).

Format (little endian):
  "LBW1", u32 count, u8 etag length, etag (ASCII)
  count x { u16 path length, u16 type length, u32 data offset, u32 data length, path, type }
  data (each file 4-byte aligned; offsets from the start of the blob)
"""

import hashlib
import pathlib
import struct

Import("env")  # noqa: F821  (injected by PlatformIO)

ROOT = pathlib.Path(env.subst("$PROJECT_DIR"))  # noqa: F821
WWW = ROOT / "www"
OUT_BIN = ROOT / "src" / "www_pack.bin"
OUT_ASM = ROOT / "src" / "www_pack.S"

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".woff2": "font/woff2",
    ".woff": "font/woff",
    ".txt": "text/plain; charset=utf-8",
}


def included(p):
    return p.is_file() and p.suffix not in (".md", ".py")


def content_type(p):
    # licence texts have no extension: shown as text in the browser, not downloaded
    if p.name.startswith("LICENSE"):
        return "text/plain; charset=utf-8"
    return TYPES.get(p.suffix, "application/octet-stream")


def pack():
    files = sorted(p for p in WWW.rglob("*") if included(p))
    entries = [(p.relative_to(WWW).as_posix(), content_type(p), p.read_bytes())
               for p in files]
    etag = hashlib.sha1(b"".join(path.encode() + data for path, _, data in entries)).hexdigest()[:16]

    header = b"LBW1" + struct.pack("<IB", len(entries), len(etag)) + etag.encode()
    table_size = sum(12 + len(path.encode()) + len(ctype.encode()) for path, ctype, _ in entries)
    offset = (len(header) + table_size + 3) & ~3
    table, blobs = b"", b""
    for path, ctype, data in entries:
        table += struct.pack("<HHII", len(path.encode()), len(ctype.encode()), offset + len(blobs), len(data))
        table += path.encode() + ctype.encode()
        blobs += data + b"\0" * (-len(data) % 4)
    blob = header + table
    blob += b"\0" * (offset - len(blob)) + blobs

    if not OUT_BIN.exists() or OUT_BIN.read_bytes() != blob:
        OUT_BIN.write_bytes(blob)
        print(f"www: {len(entries)} files, {len(blob) // 1024} KB, etag {etag}")
    asm = (f"/* generated by tools/pack_www.py, www etag {etag} */\n"
           "    .section .rodata.www_pack\n"
           "    .global www_pack_start\n"
           "    .global www_pack_end\n"
           "    .balign 4\n"
           "www_pack_start:\n"
           f"    .incbin \"{OUT_BIN.as_posix()}\"\n"
           "www_pack_end:\n")
    if not OUT_ASM.exists() or OUT_ASM.read_text() != asm:
        OUT_ASM.write_text(asm)


pack()
