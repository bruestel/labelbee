#!/usr/bin/env python3
"""Writes www/vendor/mdi-names.js, the Material Design Icons' names and code points, from the
@mdi/font package's CSS (css/materialdesignicons.css of the version whose webfont is in www/vendor/).

    tools/gen_mdi.py path/to/materialdesignicons.css

Compact: the icons sorted by code point, separated by spaces; a name stands for the code point after
the previous one, "name~d" for one d (hex) further on. The first entry carries its full code point.
"""

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "www" / "vendor" / "mdi-names.js"


def main() -> None:
    css = Path(sys.argv[1]).read_text(encoding="utf-8")
    icons = sorted(
        (int(code, 16), name)
        for name, code in re.findall(r'\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)"', css)
    )
    if not icons:
        sys.exit("no icons found")
    parts = []
    prev = None
    for code, name in icons:
        if prev is None:
            parts.append(f"{name}~{code:x}")
        elif code == prev + 1:
            parts.append(name)
        else:
            parts.append(f"{name}~{code - prev:x}")
        prev = code
    OUT.write_text(
        "// Generated by tools/gen_mdi.py from @mdi/font's CSS: Material Design Icons, names and code points.\n"
        "// Format: see tools/gen_mdi.py. Decoded by mdiIcons() in app.js.\n"
        f'const MDI_NAMES = "{" ".join(parts)}";\n',
        encoding="utf-8",
    )
    print(f"{len(icons)} icons -> {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
